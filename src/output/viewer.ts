const SCRIPT = `
(function(){
  var report = JSON.parse(document.getElementById('data').textContent);
  var SEV = ['critical','high','medium','low','info'];
  var SEVCLS = {critical:'crit',high:'high',medium:'med',low:'low',info:'info'};
  var state = { q:'', sev:new Set(), pq:new Set() };

  document.getElementById('target').textContent = report.target;
  document.getElementById('when').textContent = 'scanned ' + report.scanned_at;

  // Summary tiles.
  var s = report.summary, tiles = document.getElementById('tiles');
  var pqVuln = report.findings.filter(function(f){return f.pq_status==='vulnerable';}).length;
  [['crit','Critical',s.critical],['high','High',s.high],['med','Medium',s.medium],['','Low',s.low],['','Info',s.info],['pq','PQ-vulnerable',pqVuln]]
    .forEach(function(t){var d=document.createElement('div');d.className='tile '+t[0];var n=document.createElement('div');n.className='n';n.textContent=t[2];var l=document.createElement('div');l.className='l';l.textContent=t[1];d.appendChild(n);d.appendChild(l);tiles.appendChild(d);});

  // Filter chips.
  var filters = document.getElementById('filters');
  SEV.forEach(function(sv){ filters.appendChild(chip(sv, state.sev)); });
  ['vulnerable','transitional','safe','unknown'].forEach(function(p){ filters.appendChild(chip(p, state.pq)); });
  function chip(label, set){var c=document.createElement('button');c.className='chip';c.type='button';c.textContent=label;c.setAttribute('aria-pressed','false');
    c.addEventListener('click',function(){var on=c.getAttribute('aria-pressed')==='true';c.setAttribute('aria-pressed',(!on).toString());if(on)set.delete(label);else set.add(label);render();});return c;}

  document.getElementById('q').addEventListener('input',function(e){state.q=e.target.value.toLowerCase();render();});

  // Asset inventory (one row per distinct algorithm).
  var assets = document.getElementById('assets'); var seen={};
  report.findings.forEach(function(f){ if(f.algorithm && !seen[f.algorithm]){seen[f.algorithm]=f;} });
  var akeys = Object.keys(seen);
  if(!akeys.length){ assets.innerHTML=''; var e=document.createElement('li');e.className='empty';e.textContent='No algorithms inventoried.';assets.appendChild(e); }
  akeys.forEach(function(k){var f=seen[k];var li=document.createElement('li');li.className='asset';var n=document.createElement('span');n.className='an';n.textContent=k;var t=document.createElement('span');t.className='tag '+pqcls(f.pq_status);t.textContent=f.pq_status;li.appendChild(n);li.appendChild(t);assets.appendChild(li);});

  function pqcls(p){return p==='vulnerable'?'vuln':p==='safe'?'safe':p==='transitional'?'trans':'';}

  function matches(f){
    if(state.sev.size && !state.sev.has(f.severity)) return false;
    if(state.pq.size && !state.pq.has(f.pq_status)) return false;
    if(state.q){var hay=(f.title+' '+f.evidence+' '+(f.algorithm||'')+' '+f.recommendation).toLowerCase();if(hay.indexOf(state.q)<0)return false;}
    return true;
  }

  function render(){
    var list=document.getElementById('findings'); list.textContent='';
    var shown=report.findings.filter(matches);
    document.getElementById('fcount').textContent='('+shown.length+' of '+report.findings.length+')';
    if(!shown.length){var e=document.createElement('div');e.className='empty';e.textContent='No findings match the current filters.';list.appendChild(e);return;}
    shown.forEach(function(f){
      var li=document.createElement('li'); li.className='f '+SEVCLS[f.severity];
      var row=document.createElement('div'); row.className='row';
      row.appendChild(el('span','badge '+SEVCLS[f.severity],f.severity));
      row.appendChild(el('span','title',f.title));
      if(f.confidence) row.appendChild(el('span','tag',f.confidence));
      row.appendChild(el('span','tag '+pqcls(f.pq_status),f.pq_status));
      row.addEventListener('click',function(){li.classList.toggle('open');});
      li.appendChild(row);
      var d=document.createElement('dl'); d.className='detail';
      addField(d,'Evidence',f.evidence,true);
      if(f.algorithm) addField(d,'Algorithm',f.algorithm,true);
      addField(d,'Recommendation',f.recommendation,false);
      if(f.references&&f.references.length){var dt=el('dt','','References');var dd=document.createElement('dd');f.references.forEach(function(r,i){if(i)dd.appendChild(document.createTextNode(' · '));if(r.url){var a=document.createElement('a');a.href=r.url;a.textContent=r.label;a.rel='noopener noreferrer';a.target='_blank';dd.appendChild(a);}else{dd.appendChild(document.createTextNode(r.label));}});d.appendChild(dt);d.appendChild(dd);}
      addField(d,'Rule',(f.ruleId||f.id)+'  ·  '+f.id,true);
      li.appendChild(d);
      list.appendChild(li);
    });
  }
  function el(tag,cls,txt){var e=document.createElement(tag);if(cls)e.className=cls;e.textContent=txt;return e;}
  function addField(dl,label,value,mono){dl.appendChild(el('dt','',label));var dd=el('dd',mono?'mono':'',value);dl.appendChild(dd);}

  render();
})();
`;
