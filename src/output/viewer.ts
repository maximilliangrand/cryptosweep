/**
 * Self-contained HTML report viewer.
 *
 * cryptosweep is a CLI, so its operational surface is honest to that: a single
 * file with no external requests, no bundler, and no network — the report JSON
 * is embedded and rendered client-side into an interactive cryptographic
 * inventory (summary, filters, drill-down to evidence and citations).
 *
 * Security: scanned repositories are untrusted, so every value from a finding is
 * inserted with textContent, never innerHTML. There is no path by which scanned
 * content becomes markup.
 */
import type { Report } from "../report";
import { VERSION } from "../version";

/** Render a report as a single self-contained, offline HTML document. */
export function toHtml(report: Report): string {
  // Escape only the </script> boundary so the JSON island cannot break out.
  const data = JSON.stringify(report).replace(/</g, "\\u003c");
  return `<!doctype html>
<html lang="en" data-theme="dark">
<head>
<meta charset="utf-8" />
<meta name="viewport" content="width=device-width, initial-scale=1" />
<title>cryptosweep — ${escapeHtml(report.target)}</title>
<style>${STYLE}</style>
</head>
<body>
<header>
  <div class="brand">cryptosweep</div>
  <div class="meta">
    <span class="target" id="target"></span>
    <span class="when" id="when"></span>
  </div>
</header>
<section class="tiles" id="tiles" aria-label="Summary"></section>
<section class="controls">
  <input type="search" id="q" placeholder="Search findings, evidence, algorithms…" aria-label="Search" />
  <div class="filters" id="filters"></div>
</section>
<main>
  <div class="col">
    <h2>Findings <span class="count" id="fcount"></span></h2>
    <ol class="findings" id="findings"></ol>
  </div>
  <aside class="col">
    <h2>Cryptographic assets</h2>
    <ul class="assets" id="assets"></ul>
  </aside>
</main>
<footer>Generated by cryptosweep v${VERSION}. Confidence reflects how the evidence was derived — <em>confirmed</em> is parsed structure; <em>low</em> is a context-sensitive heuristic. Not a substitute for a credentialed cryptographer's review.</footer>
<script id="data" type="application/json">${data}</script>
<script>${SCRIPT}</script>
</body>
</html>
`;
}

function escapeHtml(value: string): string {
  return value
    .replace(/&/g, "&amp;")
    .replace(/</g, "&lt;")
    .replace(/>/g, "&gt;")
    .replace(/"/g, "&quot;");
}

